-- CREACION DE TABLAS
CREATE TABLE USUARIOS
(
    ID_USUARIO NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    USERNAME   VARCHAR2(20 BYTE) NOT NULL,
    PASSWORD   VARCHAR2(200 BYTE) NOT NULL,
    ROL        VARCHAR2(50 BYTE) NOT NULL,
    ESTADO_REGISTRO VARCHAR2(20 BYTE) DEFAULT 'ACTIVO',

    CONSTRAINT USUARIO_PK PRIMARY KEY (ID_USUARIO)
);

CREATE UNIQUE INDEX USUARIO_USERNAME_ACTIVO_UK
    ON USUARIOS (
                     CASE
                         WHEN ESTADO_REGISTRO = 'ACTIVO' THEN USERNAME
    END
        );

CREATE TABLE HUESPEDES
(
    ID_HUESPED       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE           VARCHAR2(50 BYTE) NOT NULL,
    APELLIDO_PATERNO VARCHAR2(50 BYTE) NOT NULL,
    APELLIDO_MATERNO VARCHAR2(50 BYTE) NOT NULL,
    NACIONALIDAD     VARCHAR2(50 BYTE) NOT NULL,
    EMAIL            VARCHAR2(100 BYTE) NOT NULL,
    TELEFONO         VARCHAR2(10 BYTE) NOT NULL,
    DOCUMENTO        VARCHAR2(20 BYTE) NOT NULL,
    ESTADO_REGISTRO  VARCHAR2(20 BYTE) DEFAULT 'ACTIVO',

    CONSTRAINT HUESPED_PK PRIMARY KEY (ID_HUESPED),

    CONSTRAINT HUESPED_TELEFONO_CHK
        CHECK (REGEXP_LIKE(TELEFONO, '^[0-9]{10}$')),

    CONSTRAINT HUESPED_ESTADO_REGISTRO_CHK
        CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO'))
);

CREATE UNIQUE INDEX HUESPED_EMAIL_ACTIVO_UK
    ON HUESPEDES (
                  CASE
                      WHEN ESTADO_REGISTRO = 'ACTIVO' THEN EMAIL
    END
        );

CREATE UNIQUE INDEX HUESPED_TELEFONO_ACTIVO_UK
    ON HUESPEDES (
                  CASE
                      WHEN ESTADO_REGISTRO = 'ACTIVO' THEN TELEFONO
    END
        );

CREATE UNIQUE INDEX HUESPED_DOCUMENTO_ACTIVO_UK
    ON HUESPEDES (
                  CASE
                      WHEN ESTADO_REGISTRO = 'ACTIVO' THEN DOCUMENTO
    END
        );


CREATE TABLE HABITACIONES
(
    ID_HABITACION     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NUMERO            NUMBER(10) NOT NULL,
    TIPO              VARCHAR2(50 BYTE) NOT NULL,
    CAPACIDAD         NUMBER(10) NOT NULL,
    PRECIO            NUMBER(10, 2) NOT NULL,
    ESTADO_HABITACION VARCHAR2(20 BYTE) DEFAULT 'DISPONIBLE',
    ESTADO_REGISTRO   VARCHAR2(20 BYTE) DEFAULT 'ACTIVO',

    CONSTRAINT HABITACION_PK PRIMARY KEY (ID_HABITACION),

    CONSTRAINT HABITACION_NUMERO_CHK
        CHECK (NUMERO > 0),

    CONSTRAINT HABITACION_PRECIO_CHK
        CHECK (PRECIO > 0),

    CONSTRAINT HABITACION_CAPACIDAD_CHK
        CHECK (CAPACIDAD > 0),

    CONSTRAINT HABITACION_TIPO_CHK
        CHECK (TIPO IN ('SENCILLA', 'DOBLE', 'SUITE')),

    CONSTRAINT HABITACION_ESTADO_HABITACION_CHK
        CHECK (
            ESTADO_HABITACION IN (
                                  'DISPONIBLE',
                                  'OCUPADA',
                                  'LIMPIEZA',
                                  'MANTENIMIENTO'
                )
            ),

    CONSTRAINT HABITACION_ESTADO_REGISTRO_CHK
        CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO'))
);

CREATE UNIQUE INDEX HABITACION_NUMERO_ACTIVO_UK
    ON HABITACIONES (
        CASE
            WHEN ESTADO_REGISTRO = 'ACTIVO' THEN NUMERO
        END
    );

CREATE TABLE RESERVAS
(
    ID_RESERVA        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_HUESPED        NUMBER(10) NOT NULL,
    ID_HABITACION     NUMBER(10) NOT NULL,
    ESTADO_RESERVA    VARCHAR2(20 BYTE) DEFAULT 'CONFIRMADA',
    ESTADO_REGISTRO   VARCHAR2(20 BYTE) DEFAULT 'ACTIVO',
    FECHA_RESERVA     DATE NOT NULL,
    FECHA_ENTRADA     DATE,
    FECHA_SALIDA      DATE,
    FECHA_CANCELACION DATE,

    CONSTRAINT RESERVA_PK
        PRIMARY KEY (ID_RESERVA),

    CONSTRAINT RESERVA_ESTADO_RESERVA_CHK
        CHECK (
            ESTADO_RESERVA IN (
                               'CONFIRMADA',
                               'EN_CURSO',
                               'FINALIZADA',
                               'CANCELADA'
                )
            ),

    CONSTRAINT RESERVA_ESTADO_REGISTRO_CHK
        CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO'))
);